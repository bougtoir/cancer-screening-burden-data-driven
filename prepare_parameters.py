def main() -> None:
    params = build_parameters()
    with open(PARAMS_OUT, "w", encoding="utf-8") as f:
        yaml.safe_dump(params, f, sort_keys=False, allow_unicode=True, default_flow_style=False)
    print(f"Wrote {PARAMS_OUT.resolve()}")


if __name__ == "__main__":
    main()
