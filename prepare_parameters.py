"""Build a data-driven parameters.yaml for the cancer-screening burden simulation.

All cancer incidence values are derived from public National Cancer Center of Japan
(Cancer Statistics in Japan, 2016-2023) and Japanese 2023 population data in the same
file. Diagnostic capacity values are derived from the MHLW 2023 Medical Facility Survey
(05sisetu05.xlsx). Test performance, pathway probabilities, and the "available for new
cancer workups" capacity share remain scenario assumptions, documented in the comments.

Run this script before simulate.py:
    python3 prepare_parameters.py
"""

